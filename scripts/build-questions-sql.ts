// Turns content/questions/*.json into supabase/content/questions.sql (multiple-choice, reviewed = false).
//
// Usage:
//   node scripts/build-questions-sql.ts
//   npx supabase db query --linked -f supabase/content/questions.sql

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'

type Mcq = {
  prompt: string
  choices: string[]
  answer: string
  explanation: string
  difficulty?: number
  source_name?: string
  source_url?: string
}
type PassageSet = { passage: string; questions: Mcq[] }
type QuestionFile = {
  source_name: string
  license: string
  topics: Record<string, (Mcq | PassageSet)[]>
}

const DIR = 'content/questions'
const LETTERS = 'ABCDEFGH'
const sql = (v: string | number | null | undefined) =>
  v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${v.replaceAll("'", "''")}'`

const lines = [`-- Generated by scripts/build-questions-sql.ts on ${new Date().toISOString()}`, 'begin;']
let count = 0

for (const file of readdirSync(DIR).filter((f) => f.endsWith('.json')).sort()) {
  const stem = file.replace(/\.json$/, '')
  const data = JSON.parse(readFileSync(`${DIR}/${file}`, 'utf8')) as QuestionFile
  for (const [topicId, items] of Object.entries(data.topics)) {
    let n = 0
    for (const item of items) {
      const group = 'passage' in item ? item.questions.map((q) => ({ ...q, passage: item.passage })) : [{ ...item, passage: null }]
      for (const q of group) {
        n++
        const answerIndex = LETTERS.indexOf(q.answer)
        if (answerIndex < 0 || answerIndex >= q.choices.length) throw new Error(`${file} ${topicId} #${n}: bad answer "${q.answer}"`)
        count++
        lines.push(
          `insert into public.questions (id, topic_id, kind, prompt, passage, choices, answer_index, answer_explanation, difficulty, source_name, source_url, license)
values (${sql(`${stem}-${topicId}-${n}`)}, ${sql(topicId)}, 'mcq', ${sql(q.prompt)}, ${sql(q.passage)}, ${sql(JSON.stringify(q.choices))}::jsonb, ${answerIndex}, ${sql(q.explanation)}, ${q.difficulty ?? 2}, ${sql(q.source_name ?? data.source_name)}, ${sql(q.source_url)}, ${sql(data.license)})
on conflict (id) do update set prompt = excluded.prompt, passage = excluded.passage, choices = excluded.choices,
  answer_index = excluded.answer_index, answer_explanation = excluded.answer_explanation,
  source_name = excluded.source_name, source_url = excluded.source_url, license = excluded.license
  where not public.questions.reviewed;`,
        )
      }
    }
  }
}

lines.push('commit;')
mkdirSync('supabase/content', { recursive: true })
writeFileSync('supabase/content/questions.sql', lines.join('\n') + '\n')
console.log(`Wrote supabase/content/questions.sql: ${count} questions`)
