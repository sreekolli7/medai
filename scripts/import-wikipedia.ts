// Imports English Wikipedia articles (CC BY-SA 4.0) as tutor source chunks, per MCAT topic.
// Each chunk records the exact article revision it came from. Everything is written as reviewed = false.
//
// Usage:
//   node scripts/import-wikipedia.ts [topic-id ...]     # writes supabase/content/wikipedia/<topic>.sql
//   for f in supabase/content/wikipedia/*.sql; do npx supabase db query --linked -f "$f"; done
// (One file per topic keeps each request under the database API's size limit.)
// Then press "Embed new content" on the Reviewer page.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

const API = 'https://en.wikipedia.org/w/api.php'
const USER_AGENT = 'MedAi-content-import/0.1 (study app; contact via repository owner)'
const LICENSE = 'CC BY-SA 4.0. Wikipedia contributors (see page history). Excerpted and split into passages.'
const SKIP_SECTIONS =
  /^(see also|references|notes|further reading|external links|bibliography|sources|citations|footnotes|gallery|works cited|in popular culture|etymology|history|society and culture|other animals|research)$/i
const MAX_CHUNK_WORDS = 220
const MIN_PARAGRAPH_WORDS = 12
const MAX_CHUNKS_PER_ARTICLE = 8

const { topics } = JSON.parse(readFileSync('content/wikipedia-sources.json', 'utf8')) as {
  topics: Record<string, string[]>
}
const only = process.argv.slice(2)
const selected = Object.entries(topics).filter(([id]) => !only.length || only.includes(id))

const words = (s: string) => s.split(/\s+/).filter(Boolean).length
const sql = (v: string) => `'${v.replaceAll("'", "''")}'`

// Plain-text extracts render math as "{\displaystyle ...}"; drop those blocks (braces can nest).
function stripMath(text: string) {
  let out = ''
  let i = 0
  while (i < text.length) {
    const start = text.indexOf('{\\displaystyle', i)
    if (start < 0) {
      out += text.slice(i)
      break
    }
    out += text.slice(i, start)
    let depth = 0
    let j = start
    for (; j < text.length; j++) {
      if (text[j] === '{') depth++
      else if (text[j] === '}' && --depth === 0) break
    }
    i = j + 1
  }
  return out.replace(/[ \t]{2,}/g, ' ').replace(/ ([.,;:])/g, '$1')
}

async function fetchArticle(title: string) {
  const params = new URLSearchParams({
    action: 'query',
    format: 'json',
    formatversion: '2',
    redirects: '1',
    prop: 'extracts|revisions',
    rvprop: 'ids',
    explaintext: '1',
    exsectionformat: 'wiki',
    titles: title,
  })
  for (let attempt = 1; attempt <= 6; attempt++) {
    const res = await fetch(`${API}?${params}`, { headers: { 'User-Agent': USER_AGENT } })
    if (res.ok) {
      const page = (await res.json()).query?.pages?.[0]
      if (!page || page.missing) throw new Error(`Wikipedia article not found: ${title}`)
      return { title: page.title as string, revid: page.revisions[0].revid as number, text: page.extract as string }
    }
    const wait = Number(res.headers.get('retry-after')) * 1000 || attempt * 5000
    console.warn(`${title}: HTTP ${res.status}, retrying in ${wait / 1000}s`)
    await new Promise((r) => setTimeout(r, wait))
  }
  throw new Error(`Couldn't fetch ${title}`)
}

function chunkArticle(title: string, text: string) {
  const chunks: { title: string; body: string }[] = []
  let heading = ''
  let skipLevel = 0
  let buffer: string[] = []
  const flush = () => {
    if (buffer.length) chunks.push({ title: heading ? `${title}: ${heading}` : title, body: buffer.join(' ') })
    buffer = []
  }

  for (const raw of stripMath(text).split('\n')) {
    const line = raw.trim()
    const h = line.match(/^(={2,6})\s*(.*?)\s*\1$/)
    if (h) {
      const level = h[1].length
      if (skipLevel && level > skipLevel) continue
      skipLevel = SKIP_SECTIONS.test(h[2]) ? level : 0
      flush()
      heading = h[2]
      continue
    }
    if (skipLevel || words(line) < MIN_PARAGRAPH_WORDS) continue
    if (words(buffer.join(' ')) + words(line) > MAX_CHUNK_WORDS) flush()
    buffer.push(line)
  }
  flush()
  return chunks.slice(0, MAX_CHUNKS_PER_ARTICLE)
}

const OUT_DIR = 'supabase/content/wikipedia'
mkdirSync(OUT_DIR, { recursive: true })
let total = 0
for (const [topicId, titles] of selected) {
  const lines = [`-- Generated by scripts/import-wikipedia.ts on ${new Date().toISOString()}`, 'begin;']
  lines.push(
    `delete from public.content_chunks where topic_id = ${sql(topicId)} and source_name like 'Wikipedia: %' and not reviewed;`,
  )
  let count = 0
  for (const requested of titles) {
    const article = await fetchArticle(requested)
    const url = `https://en.wikipedia.org/w/index.php?title=${encodeURIComponent(article.title.replaceAll(' ', '_'))}&oldid=${article.revid}`
    for (const c of chunkArticle(article.title, article.text)) {
      count++
      lines.push(
        `insert into public.content_chunks (topic_id, title, body, source_name, source_url, license)
select ${sql(topicId)}, ${sql(c.title)}, ${sql(c.body)}, ${sql(`Wikipedia: ${article.title}`)}, ${sql(url)}, ${sql(LICENSE)}
where not exists (select 1 from public.content_chunks where topic_id = ${sql(topicId)} and body = ${sql(c.body)});`,
      )
    }
    await new Promise((r) => setTimeout(r, 1000))
  }
  lines.push('commit;')
  writeFileSync(`${OUT_DIR}/${topicId}.sql`, lines.join('\n') + '\n')
  total += count
  console.log(`${topicId}: ${count} chunks from ${titles.length} articles`)
}
console.log(`Wrote ${selected.length} files to ${OUT_DIR}: ${total} chunks`)
