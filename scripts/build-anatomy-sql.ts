// Turns content/anatomy/parts.json into supabase/content/anatomy.sql: parts for the brain, eye,
// torso and skeleton models (reviewed = false) and links from questions to the part they're about.
//
// Usage:
//   node scripts/build-anatomy-sql.ts
//   npx supabase db query --linked -f supabase/content/anatomy.sql

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

type PartEntry = {
  id: string
  name: string
  topic: string
  explanation: string
  pearl: string
  blood?: 'oxygen-poor' | 'oxygen-rich'
}
type AnatomyFile = { models: Record<string, PartEntry[]>; links: Record<string, string> }

const HEART_PARTS = new Set([
  'superior-vena-cava',
  'right-atrium',
  'right-ventricle',
  'pulmonary-artery',
  'pulmonary-veins',
  'left-atrium',
  'left-ventricle',
  'aorta',
])

const sql = (v: string | number | null | undefined) =>
  v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${v.replaceAll("'", "''")}'`

const data = JSON.parse(readFileSync('content/anatomy/parts.json', 'utf8')) as AnatomyFile
const lines = [`-- Generated by scripts/build-anatomy-sql.ts on ${new Date().toISOString()}`, 'begin;']
const known = new Set(HEART_PARTS)
let parts = 0

for (const [model, entries] of Object.entries(data.models)) {
  entries.forEach((p, i) => {
    if (!p.id.startsWith(`${model}-`)) throw new Error(`${p.id}: part ids must start with "${model}-"`)
    known.add(p.id)
    parts++
    lines.push(
      `insert into public.parts (id, model, topic_id, name, side, blood, sort_order, explanation, exam_pearl)
values (${sql(p.id)}, ${sql(model)}, ${sql(p.topic)}, ${sql(p.name)}, null, ${sql(p.blood ?? null)}, ${i + 1}, ${sql(p.explanation)}, ${sql(p.pearl)})
on conflict (id) do update set model = excluded.model, topic_id = excluded.topic_id, name = excluded.name,
  blood = excluded.blood, sort_order = excluded.sort_order, explanation = excluded.explanation, exam_pearl = excluded.exam_pearl
  where not public.parts.reviewed;`,
    )
  })
}

lines.push('update public.questions set related_part_id = null where related_part_id is not null;')
for (const [questionId, partId] of Object.entries(data.links)) {
  if (!known.has(partId)) throw new Error(`${questionId}: unknown part "${partId}"`)
  lines.push(`update public.questions set related_part_id = ${sql(partId)} where id = ${sql(questionId)};`)
}

lines.push('commit;')
mkdirSync('supabase/content', { recursive: true })
writeFileSync('supabase/content/anatomy.sql', lines.join('\n') + '\n')
console.log(`Wrote supabase/content/anatomy.sql: ${parts} parts, ${Object.keys(data.links).length} question links`)
